/**
 * Every topic check and lab in content/ must validate, and every check must be passable
 * with its own answer key (so a typo in a key cannot lock a topic).
 */
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { validateLabSpec } from './index';
import { drawItems, gradeCheck, type CheckAnswer, type CheckItem, type TopicCheckSpec, validateTopicCheckSpec } from './topicCheck';

const CONTENT = join(__dirname, '../../../content/courses');

function keyedAnswer(item: CheckItem): CheckAnswer {
  switch (item.type) {
    case 'choice':
      return item.answer;
    case 'multi':
      return item.answer;
    case 'numeric':
      return String(item.answer);
    case 'text':
      return (item as { example?: string }).example ?? sampleFromPattern(item.pattern);
  }
}

/** Finds a string matching a simple pattern by trying the explanation's code spans or literal alternatives. */
function sampleFromPattern(pattern: string): string {
  // Patterns in our content are literals, optional prefixes (0*, (0x)?, 0?) or alternations of literals.
  const first = pattern.split('|')[0];
  return first
    .replace(/\(0x\)\?/g, '')
    .replace(/0\*/g, '')
    .replace(/0\?/g, '')
    .replace(/\\s\*|\\s\?/g, ' ')
    .replace(/\[·\*\]\?/g, '')
    .replace(/\[([^\]])[^\]]*\]/g, '$1')
    .replace(/\\\./g, '.')
    .replace(/0\*$/, '');
}

const courses = readdirSync(CONTENT).filter((d) => statSync(join(CONTENT, d)).isDirectory());

describe('lab content', () => {
  for (const course of courses) {
    const dir = join(CONTENT, course);
    const files = readdirSync(dir).filter((f) => f.endsWith('.json'));
    for (const f of files) {
      it(`${course}/${f} is a valid lab spec`, () => {
        const raw = JSON.parse(readFileSync(join(dir, f), 'utf8'));
        expect(validateLabSpec(raw)).toBe(true);
        expect(raw.course).toBe(course);
      });
    }
  }
});

describe('topic check content', () => {
  for (const course of courses) {
    const dir = join(CONTENT, course, 'checks');
    let files: string[] = [];
    try {
      files = readdirSync(dir).filter((f) => f.endsWith('.json'));
    } catch {
      continue;
    }
    for (const f of files) {
      const spec = JSON.parse(readFileSync(join(dir, f), 'utf8')) as TopicCheckSpec;
      it(`${course}/checks/${f} validates and matches its file name`, () => {
        expect(validateTopicCheckSpec(spec)).toBe(true);
        expect(spec.course).toBe(course);
        expect(f).toBe(`${spec.unit}-${spec.topic}.json`);
        expect(spec.items.length).toBeGreaterThanOrEqual(8);
      });
      it(`${course}/checks/${f} passes with its own answer key, on several draws`, () => {
        for (const seed of [1, 2, 3, 4, 5]) {
          const items = drawItems(spec, seed);
          const answers = Object.fromEntries(items.map((it) => [it.id, keyedAnswer(it)]));
          const grade = gradeCheck(items, answers, spec.passMark);
          const wrong = grade.items.filter((g) => !g.correct).map((g) => g.id);
          expect(wrong, `items whose key does not match their own pattern: ${wrong.join(', ')}`).toEqual([]);
          expect(grade.passed).toBe(true);
          expect(grade.score).toBe(100);
        }
      });
      it(`${course}/checks/${f} gives a wrong answer no credit`, () => {
        const items = drawItems(spec, 7);
        const answers: Record<string, CheckAnswer> = Object.fromEntries(
          items.map((it) => [it.id, it.type === 'choice' ? (it.answer + 1) % it.options.length : it.type === 'multi' ? [] : 'nonsense']),
        );
        const grade = gradeCheck(items, answers, spec.passMark);
        expect(grade.correct).toBe(0);
        expect(grade.passed).toBe(false);
      });
    }
  }
});

/* The catalogue (data/courses.json, generated by scripts/build-courses.mjs) and its programmes. */
describe('catalogue and programmes', () => {
  const DATA = join(__dirname, '../../../data');
  const catalogue = JSON.parse(readFileSync(join(DATA, 'courses.json'), 'utf8')) as {
    areas: Record<string, string>;
    programmes: Array<{
      slug: string;
      title: string;
      description: string;
      outcomes: string[];
      courses: string[];
      levels?: Record<'bachelor' | 'master' | 'phd', { award: string; core: string[]; electives: string[]; electivesRequired: number }>;
    }>;
    courses: Array<{
      slug: string;
      title: string;
      area: string;
      engines: string[];
      description?: string;
      syllabus?: Array<{ title: string; topics: string[] }>;
      weeks?: number;
    }>;
  };
  type Week = { week: number; topics: string[]; exercise: string; tasks: Array<{ level: string; topic: string; engine: string }> };
  const scheduleOf = (slug: string): Week[] =>
    JSON.parse(readFileSync(join(DATA, 'syllabi', `${slug}.json`), 'utf8')).schedule ?? [];
  const slugs = new Set(catalogue.courses.map((c) => c.slug));
  const ENGINES = new Set(['E1', 'E2', 'E3', 'E4', 'E5', 'E6', 'E7', 'E8', 'E9', 'E10', 'E11', 'E12']);
  const NAMES = /\b(HTU|Ho Technical|MIT|Stanford|Berkeley|Carnegie Mellon|Harvard University|Oxford University|University of Cambridge|Princeton|Coursera|edX|Udacity)\b/;

  it('has programmes, each listing known courses once', () => {
    expect(catalogue.programmes.length).toBeGreaterThanOrEqual(11);
    for (const p of catalogue.programmes) {
      expect(p.courses.length, p.slug).toBeGreaterThanOrEqual(10);
      expect(new Set(p.courses).size, `${p.slug} repeats a course`).toBe(p.courses.length);
      for (const s of p.courses) expect(slugs.has(s), `${p.slug} lists unknown course ${s}`).toBe(true);
      expect(p.outcomes.length).toBeGreaterThanOrEqual(3);
    }
  });

  it('puts every course in at least one programme', () => {
    const used = new Set(
      catalogue.programmes.flatMap((p) => [
        ...p.courses,
        ...Object.values(p.levels ?? {}).flatMap((l) => [...l.core, ...l.electives]),
      ]),
    );
    expect(catalogue.courses.filter((c) => !used.has(c.slug)).map((c) => c.slug)).toEqual([]);
  });

  it('gives every course a known area, simulation engines and a full syllabus file', () => {
    const files = new Set(readdirSync(join(DATA, 'syllabi')).map((f) => f.replace(/\.json$/, '')));
    for (const c of catalogue.courses) {
      expect(catalogue.areas[c.area], `${c.slug} area`).toBeTruthy();
      expect(c.engines.length, `${c.slug} engines`).toBeGreaterThan(0);
      for (const e of c.engines) expect(ENGINES.has(e), `${c.slug} engine ${e}`).toBe(true);
      expect(files.has(c.slug), `${c.slug} has no data/syllabi file`).toBe(true);
      expect(c.syllabus?.length ?? 0, `${c.slug} units`).toBeGreaterThanOrEqual(7);
      for (const u of c.syllabus ?? []) expect(u.topics.length, `${c.slug}: ${u.title}`).toBeGreaterThanOrEqual(4);
    }
  });

  it('lays every course out as 12 or 13 weeks with tasks at three levels on its own topics', () => {
    for (const c of catalogue.courses) {
      const refs = new Set((c.syllabus ?? []).flatMap((u, i) => u.topics.map((_, t) => `${i + 1}.${t + 1}`)));
      const weeks = scheduleOf(c.slug);
      expect(c.weeks, `${c.slug} week count in the catalogue`).toBe(weeks.length);
      expect(weeks.length, `${c.slug} weeks`).toBeGreaterThanOrEqual(12);
      expect(weeks.length, `${c.slug} weeks`).toBeLessThanOrEqual(13);
      const taught = new Set(weeks.flatMap((w) => w.topics));
      expect([...refs].filter((r) => !taught.has(r)), `${c.slug} unscheduled topics`).toEqual([]);
      for (const w of weeks) {
        expect(w.exercise, `${c.slug} week ${w.week} exercise`).toBeTruthy();
        for (const level of ['beginner', 'intermediate', 'advanced'])
          expect(w.tasks.some((t) => t.level === level), `${c.slug} week ${w.week} ${level}`).toBe(true);
        for (const t of w.tasks) {
          expect(ENGINES.has(t.engine), `${c.slug} week ${w.week} engine ${t.engine}`).toBe(true);
          expect(w.topics.includes(t.topic) && refs.has(t.topic), `${c.slug} week ${w.week} topic ${t.topic}`).toBe(true);
        }
      }
    }
  });

  it('gives every programme bachelor, master and doctoral levels', () => {
    for (const p of catalogue.programmes) {
      for (const tier of ['bachelor', 'master', 'phd'] as const) {
        const l = p.levels?.[tier];
        expect(l, `${p.slug} ${tier}`).toBeTruthy();
        if (!l) continue;
        expect(l.award, `${p.slug} ${tier} award`).toBeTruthy();
        expect(l.core.length, `${p.slug} ${tier} core`).toBeGreaterThan(0);
        for (const s of [...l.core, ...l.electives]) expect(slugs.has(s), `${p.slug} ${tier} lists unknown ${s}`).toBe(true);
        expect(l.electivesRequired).toBeLessThanOrEqual(l.electives.length);
      }
      expect(p.courses).toEqual([...p.levels!.bachelor.core, ...p.levels!.bachelor.electives]);
    }
  });

  it('names no university or course platform', () => {
    const text = JSON.stringify({ programmes: catalogue.programmes, courses: catalogue.courses.map(({ slug, title, syllabus, description }) => ({ slug, title, syllabus, description, schedule: scheduleOf(slug) })) });
    expect(text.match(NAMES)?.[0] ?? null).toBeNull();
  });
});
