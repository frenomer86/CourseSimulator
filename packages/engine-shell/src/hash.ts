/** Real SHA-256, SHA-1 and MD5 digests of UTF-8 text, so checksums match the real tools. No imports. */

function utf8(s: string): Uint8Array {
  return new TextEncoder().encode(s);
}

const hex = (words: number[], littleEndian = false) =>
  words
    .map((w) => {
      const v = littleEndian ? ((w & 0xff) << 24) | ((w & 0xff00) << 8) | ((w >>> 8) & 0xff00) | (w >>> 24) : w;
      return (v >>> 0).toString(16).padStart(8, '0');
    })
    .join('');

/** Pads a message to whole 64-byte blocks with its bit length, big- or little-endian. */
function pad(bytes: Uint8Array, littleEndian: boolean): Uint8Array {
  const len = bytes.length;
  const total = Math.ceil((len + 9) / 64) * 64;
  const out = new Uint8Array(total);
  out.set(bytes);
  out[len] = 0x80;
  const bits = len * 8;
  const hi = Math.floor(bits / 0x100000000);
  const lo = bits >>> 0;
  for (let i = 0; i < 4; i++) {
    if (littleEndian) {
      out[total - 8 + i] = (lo >>> (8 * i)) & 0xff;
      out[total - 4 + i] = (hi >>> (8 * i)) & 0xff;
    } else {
      out[total - 1 - i] = (lo >>> (8 * i)) & 0xff;
      out[total - 5 - i] = (hi >>> (8 * i)) & 0xff;
    }
  }
  return out;
}

