-- ---------------------------------------------------------------------------
-- Competitions
-- ---------------------------------------------------------------------------
create table competitions (
  id             uuid primary key default gen_random_uuid(),
  kind           competition_kind not null,
  status         competition_status not null default 'draft',
  title          text not null check (char_length(title) between 3 and 160),
  description    text check (char_length(description) <= 4000),
  course_slug    text,                     -- optional focus
  group_id       uuid references groups (id) on delete cascade,  -- group contests and quests live inside a group
  created_by     uuid not null references users (id) on delete cascade,
  starts_at      timestamptz not null,
  ends_at        timestamptz not null,
  team_min       smallint not null default 1,
  team_max       smallint not null default 1,
  hint_penalty   numeric(3,2) not null default 0.20,
  wrong_run_penalty_s integer not null default 300,
  rules          jsonb not null default '{}'::jsonb,   -- quests: {"goal": n}
  finished_at    timestamptz,
  created_at     timestamptz not null default now(),
  check (ends_at > starts_at),
  check (team_min >= 1 and team_max >= team_min)
);
create index competitions_group_idx on competitions (group_id, starts_at desc);
create index competitions_status_idx on competitions (status, starts_at desc);

create table competition_problems (
  competition_id uuid not null references competitions (id) on delete cascade,
  ordinal        smallint not null,
  kind           text not null check (kind in ('lab', 'check')),
  content_id     text not null,            -- lab id, or check key course:unit:topic
  level          text,                     -- lab level, for the contribution breakdown
  points         integer not null check (points > 0),
  primary key (competition_id, ordinal)
);

create table competition_teams (
  id             uuid primary key default gen_random_uuid(),
  competition_id uuid not null references competitions (id) on delete cascade,
  group_id       uuid references groups (id) on delete set null,
  name           text not null check (char_length(name) between 2 and 60),
  created_by     uuid references users (id) on delete set null,
  created_at     timestamptz not null default now(),
  unique (competition_id, name)
);

create table competition_participants (
  competition_id uuid not null references competitions (id) on delete cascade,
  user_id        uuid not null references users (id) on delete cascade,
  team_id        uuid references competition_teams (id) on delete set null,
  joined_at      timestamptz not null default now(),
  primary key (competition_id, user_id)
);

create table competition_submissions (
  id             bigint generated always as identity primary key,
  competition_id uuid not null references competitions (id) on delete cascade,
  ordinal        smallint not null,
  user_id        uuid not null references users (id) on delete cascade,
  passed         boolean not null,
  hints_used     smallint not null default 0,
  submitted_at   timestamptz not null default now(),
  foreign key (competition_id, ordinal) references competition_problems (competition_id, ordinal) on delete cascade
);
create index competition_submissions_idx on competition_submissions (competition_id, user_id, ordinal);

-- Maintained by trigger: one row per participant, recomputed on each submission.
create table competition_scores (
  competition_id uuid not null references competitions (id) on delete cascade,
  user_id        uuid not null references users (id) on delete cascade,
  team_id        uuid references competition_teams (id) on delete set null,
  points         integer not null default 0,
  solved         smallint not null default 0,
  penalty_s      integer not null default 0,
  finish_s       integer not null default 0,   -- time of last accepted solve since start + penalties
  contributions  jsonb not null default '{}'::jsonb, -- {beginner, intermediate, advanced, checks, answers, resources}
  updated_at     timestamptz not null default now(),
  primary key (competition_id, user_id)
);
create index competition_scores_board_idx on competition_scores (competition_id, points desc, finish_s asc);

create table awards (
  id             bigint generated always as identity primary key,
  user_id        uuid not null references users (id) on delete cascade,
  competition_id uuid references competitions (id) on delete cascade,
  team_id        uuid references competition_teams (id) on delete set null,
  kind           award_kind not null,
  label          text not null,
  awarded_at     timestamptz not null default now()
);
create index awards_user_idx on awards (user_id, awarded_at desc);
create index awards_competition_idx on awards (competition_id);

