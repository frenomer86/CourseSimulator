-- Community and competitions (docs/03-PRODUCT-SPEC.md sections 5 to 7), ported from
-- docs/reference/community-and-competition-schema.sql. That file was written for Supabase:
-- its auth.users references become users, and its row-level-security policies are enforced
-- by the API route handlers (apps/api/src/community.ts, forum.ts, messages.ts, competitions.ts).
-- Content ids (course slugs, lab ids, check keys) are strings into the app bundle.

-- ---------------------------------------------------------------------------
-- Enumerations
-- ---------------------------------------------------------------------------
create type platform_role as enum ('learner', 'facilitator', 'moderator', 'admin');
create type group_kind as enum ('study', 'class', 'team');
create type group_role as enum ('owner', 'admin', 'member');
create type group_visibility as enum ('public', 'invite');
create type resource_kind as enum ('link', 'note', 'file', 'solution');
create type competition_kind as enum ('general', 'group', 'league', 'quest');
create type competition_status as enum ('draft', 'scheduled', 'live', 'scoring', 'finished', 'cancelled');
create type award_kind as enum ('gold', 'silver', 'bronze', 'first_solve', 'most_helpful', 'top_contributor', 'tier', 'quest');
create type report_status as enum ('open', 'actioned', 'dismissed');

