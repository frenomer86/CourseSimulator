-- ---------------------------------------------------------------------------
-- Groups
-- ---------------------------------------------------------------------------
create table groups (
  id          uuid primary key default gen_random_uuid(),
  kind        group_kind not null default 'study',
  name        text not null check (char_length(name) between 3 and 80),
  description text check (char_length(description) <= 1000),
  visibility  group_visibility not null default 'public',
  course_slug text,
  join_code   text unique not null,                      -- short code, generated by the API
  created_by  uuid not null references users (id) on delete cascade,
  created_at  timestamptz not null default now()
);

create table group_members (
  group_id  uuid not null references groups (id) on delete cascade,
  user_id   uuid not null references users (id) on delete cascade,
  role      group_role not null default 'member',
  joined_at timestamptz not null default now(),
  primary key (group_id, user_id)
);
create index group_members_user_idx on group_members (user_id);

create table group_messages (
  id         bigint generated always as identity primary key,
  group_id   uuid not null references groups (id) on delete cascade,
  user_id    uuid not null references users (id) on delete cascade,
  body       text not null check (char_length(body) between 1 and 4000),
  reply_to   bigint references group_messages (id) on delete set null,
  created_at timestamptz not null default now(),
  deleted_at timestamptz
);
create index group_messages_group_idx on group_messages (group_id, created_at desc);

-- A facilitator's "simulation task": labs and topic checks for a group to complete, with an
-- optional deadline. Completion is read from lab_results and check_attempts.
create table group_tasks (
  id          uuid primary key default gen_random_uuid(),
  group_id    uuid not null references groups (id) on delete cascade,
  created_by  uuid not null references users (id) on delete cascade,
  title       text not null check (char_length(title) between 3 and 160),
  description text check (char_length(description) <= 2000),
  items       jsonb not null,                            -- [{kind:'lab'|'check', id:'...'}]
  due_at      timestamptz,
  created_at  timestamptz not null default now()
);
create index group_tasks_group_idx on group_tasks (group_id, created_at desc);

-- ---------------------------------------------------------------------------
-- Resources: links, notes and solution shares, in a group or a course's public library
-- ---------------------------------------------------------------------------
create table resources (
  id          uuid primary key default gen_random_uuid(),
  kind        resource_kind not null,
  owner_id    uuid not null references users (id) on delete cascade,
  group_id    uuid references groups (id) on delete cascade,     -- null = course public library
  course_slug text,
  lab_id      text,                                               -- for solution shares
  title       text not null check (char_length(title) between 1 and 160),
  body        text check (char_length(body) <= 20000),            -- note text or description
  url         text check (char_length(url) <= 2000),
  payload     jsonb,                                              -- the shared circuit or code
  created_at  timestamptz not null default now(),
  check (group_id is not null or course_slug is not null),
  check (kind <> 'solution' or lab_id is not null)
);
create index resources_group_idx on resources (group_id, created_at desc);
create index resources_course_idx on resources (course_slug, created_at desc);

